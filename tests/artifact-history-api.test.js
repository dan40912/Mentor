import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,mkdir,writeFile,rm} from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {randomUUID} from 'node:crypto';
import {ArtifactHistory} from '../src/artifact-history.js';
import {serializeTask,sha256} from '../src/tasks.js';
import {demoTask} from './fixtures/demo-task.js';
import {requestApp} from './fixtures/request.js';
test('authenticated version API binds task, manifest, index and filename and refuses corrupted history',async t=>{
 const root=await mkdtemp(path.join(os.tmpdir(),'mentor-history-api-'));t.after(()=>rm(root,{recursive:true,force:true}));
 const vault=path.join(root,'vault'),outputs=path.join(root,'outputs');await mkdir(vault);await mkdir(outputs);
 const task=demoTask('TASK-history-api',outputs),history=new ArtifactHistory(vault),turnId=randomUUID();
 await writeFile(path.join(outputs,'note.md'),'# saved <script>bad()</script>');
 const version=await history.capture(task,{turnId,phase:'after',outputs:[{file:'note.md',sha:sha256('# saved <script>bad()</script>')}]});
 task.planning.learningTurns=[{id:turnId,artifactHistory:{after:{id:version.id,digest:version.digest}}}];
 await writeFile(path.join(vault,task.id+'.md'),serializeTask(task));await writeFile(path.join(outputs,'note.md'),'new current contents');
 const app=await requestApp(root),url=`/api/tasks/${task.id}/artifact-version?version=${version.id}`;
 assert.equal((await app.fetch(url)).status,403);
 const home=await app.fetch('/'),cookie=home.headers.get('set-cookie').split(';')[0],get=url=>app.fetch(url,{headers:{cookie}});
 assert.equal((await get(url)).status,200);const saved=await get(url+'&index=0&file=note.md');assert.equal(saved.status,200);
 assert.equal(saved.headers.get('x-mentor-artifact-sha256'),version.files[0].sha);assert.match(await saved.text(),/&lt;script&gt;/);
 assert.equal((await get(url+'&index=0&file=other.md')).status,400);assert.equal((await get(url+'&index=01&file=note.md')).status,400);
 assert.equal((await get(`/api/tasks/${task.id}/artifact-version?version=${randomUUID()}`)).status,404);
 await writeFile(path.join(vault,'artifact-history',task.id,version.id,'manifest.json'),JSON.stringify({...version,revision:99}));
 const corrupt=await get(url+'&index=0&file=note.md');assert.equal(corrupt.status,409);assert.equal((await corrupt.json()).code,'ARTIFACT_HISTORY_CORRUPT');
});

test('D and F preserve distinct bytes; failed writes keep before snapshot; trash restore and purge include copies',async t=>{
 const root=await mkdtemp(path.join(os.tmpdir(),'mentor-history-flow-'));t.after(()=>rm(root,{recursive:true,force:true}));
 let mode='one',id;
 const app=await requestApp(root,async input=>{
  if(input.mode!=='write')return {text:JSON.stringify(input.prompt.includes('「任務制定」')?{card:{title:'版本測試',goal:'保留成果',project:'demo'}}:{questions:[],ready:true})};
  const task=await app.coach.latest(id);await writeFile(path.join(task.allowedRoots[0],'result.txt'),mode);
  if(mode==='failure')throw new Error('simulated failed write');
  return {text:'STATUS: DONE\nFILES: '+(mode==='empty'?'':'result.txt')};
 });
 const created=await app.coach.create({request:'版本測試',profile:'quick'});id=created.task.id;await app.settle();
 await app.coach.store.mutate(id,'latest',null,task=>{task.planning.phase='execute';task.planning.card.testCommand='';task.planning.outline={storyline:'成果',logic:[],sections:[],imageTotal:0};task.planning.workItems=[{id:'W1',title:'成果',detail:'',owner:'ai',acceptance:['成果'],dependsOn:[],status:'TODO',attempts:0}];return {};});
 await (await app.coach.execute(id,'W1')).done;
 let task=await app.coach.latest(id),first=task.planning.learningTurns.at(-1);assert.equal(first.status,'completed');assert.ok(first.outputs[0].snapshot);
 const read=async ref=>(await app.coach.artifactHistory.read(id,ref.id,0)).content.toString();
 assert.equal(await read(first.artifactHistory.after),'one');
 await app.coach.store.mutate(id,'latest',null,task=>{task.planning.workItems[0].status='REVIEW_FAIL';return {};});mode='two';
 await (await app.coach.execute(id,'W1','F')).done;task=await app.coach.latest(id);const second=task.planning.learningTurns.at(-1);
 assert.equal(await read(second.artifactHistory.before),'one');assert.equal(await read(second.artifactHistory.after),'two');assert.equal(await read(first.artifactHistory.after),'one');
 await app.coach.store.mutate(id,'latest',null,task=>{task.planning.workItems[0].status='REVIEW_FAIL';return {};});mode='failure';
 await (await app.coach.execute(id,'W1','F')).done;task=await app.coach.latest(id);const failed=task.planning.learningTurns.at(-1);
 assert.equal(failed.status,'failed');assert.equal(await read(failed.artifactHistory.before),'two');assert.equal(failed.artifactHistory.after,undefined);
 await app.coach.store.mutate(id,'latest',null,task=>{task.planning.workItems[0].status='REVIEW_FAIL';return {};});mode='empty';
 await (await app.coach.execute(id,'W1','F')).done;task=await app.coach.latest(id);
 assert.equal(task.planning.workItems[0].status,'BLOCKED');assert.deepEqual(task.planning.learningTurns.at(-1).outputs,[]);
 assert.equal(task.planning.learningTurns.at(-1).artifactHistory.after,undefined);
 const {Trash}=await import('../src/trash.js'),trash=new Trash(path.join(root,'vault'),app.coach.store,app.coach);
 const removed=await trash.trashTask(id);assert.ok(removed.trashed.files.includes('artifact-history/'+id));
 await assert.rejects(app.coach.artifactHistory.read(id,first.artifactHistory.after.id,0),{code:'ARTIFACT_HISTORY_MISSING'});
 await trash.restore(removed.trashed.id);assert.equal(await read(first.artifactHistory.after),'one');
 const again=await trash.trashTask(id);await trash.purge(again.trashed.id,{confirm:again.trashed.name});
 const {readFile}=await import('node:fs/promises');assert.equal(await readFile(path.join(task.allowedRoots[0],'result.txt'),'utf8'),'empty');
 await assert.rejects(app.coach.artifactHistory.read(id,first.artifactHistory.after.id,0),{code:'ARTIFACT_HISTORY_MISSING'});
});
