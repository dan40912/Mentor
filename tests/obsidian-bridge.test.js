import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import path from 'node:path';
import { tmpdir } from 'node:os';
import { ObsidianBridge } from '../src/obsidian-bridge.js';
import { requestApp } from './fixtures/request.js';

const request = (token, url='/api/obsidian/tasks', method='GET') => ({url,method,headers:{authorization:'Bearer '+token}});
test('pairing is single use, short lived, rate limited and revocable; credentials have a finite lifetime', () => {
  let clock=1000;const bridge=new ObsidianBridge(()=>clock);
  const pairing=bridge.prepare();
  assert.throws(()=>bridge.exchange('wrong'),{code:'PAIRING_INVALID'});
  const access=bridge.exchange(pairing.code);
  assert.equal(bridge.authorize(request(access.token)).route,'/api/tasks');
  assert.throws(()=>bridge.exchange(pairing.code),{code:'PAIRING_INVALID'});
  assert.ok(!JSON.stringify(bridge.list()).includes(access.token));
  assert.equal(bridge.authorize(request(access.token,'/api/obsidian/tasks/TASK-a/ask','POST')).route,'/api/tasks/TASK-a/ask');
  for(const route of ['/api/obsidian/settings','/api/obsidian/handoffs','/api/obsidian/tasks/TASK-a/trash','/api/obsidian/tasks/TASK-a/../../settings'])assert.throws(()=>bridge.authorize(request(access.token,route,'POST')),{code:'BRIDGE_SCOPE'});
  bridge.revoke(access.id);assert.throws(()=>bridge.authorize(request(access.token)),{code:'BRIDGE_AUTH_REQUIRED'});
  const expiring=bridge.prepare();clock+=120001;assert.throws(()=>bridge.exchange(expiring.code),{code:'PAIRING_INVALID'});
  const fresh=bridge.exchange(bridge.prepare().code);clock+=12*60*60*1000;assert.throws(()=>bridge.authorize(request(fresh.token)),{code:'BRIDGE_AUTH_REQUIRED'});
  for(let i=0;i<12;i++)assert.throws(()=>bridge.exchange('bad'),{code:'PAIRING_INVALID'});
  assert.throws(()=>bridge.exchange('bad'),{code:'PAIRING_RATE_LIMIT'});
});

test('HTTP bridge retains origin/CSRF checks, scopes writes and revokes immediately', async t => {
  const home=await mkdtemp(path.join(tmpdir(),'mentor-bridge-'));t.after(()=>rm(home,{recursive:true,force:true}));
  const app=await requestApp(home);
  const cookie=(await app.fetch('/')).headers.get('set-cookie').split(';')[0];
  const csrfToken=(await(await app.fetch('/api/session',{headers:{cookie}})).json()).csrfToken;
  const session={cookie,'x-csrf-token':csrfToken,'content-type':'application/json'};
  const post=(url,input,headers=session)=>app.fetch(url,{method:'POST',headers,body:JSON.stringify(input)});
  assert.equal((await post('/api/obsidian/pairing',{},{})).status,403);
  const pair=await(await post('/api/obsidian/pairing',{})).json();
  assert.equal((await post('/api/obsidian/connect',{code:pair.code},{origin:'https://untrusted.example'})).status,403);
  const access=await(await post('/api/obsidian/connect',{code:pair.code},{})).json();
  const bearer={authorization:'Bearer '+access.token,'content-type':'application/json'};
  assert.equal((await app.fetch('/api/obsidian/tasks',{headers:bearer})).status,200);
  assert.equal((await post('/api/obsidian/settings',{},bearer)).status,403);
  assert.equal((await post('/api/obsidian/tasks',{request:'不准指定任意路徑',outputDir:'/elsewhere'},bearer)).status,403);
  assert.equal((await post('/api/obsidian/tasks',{request:'不准偷偷自動執行',autopilot:true},bearer)).status,403);
  const createHeaders={...bearer,'idempotency-key':'plugin-create-001'};
  const created=await post('/api/obsidian/tasks',{request:'根據虛構筆記擬一份指南',profile:'quick'},createHeaders);
  assert.equal(created.status,202);await app.settle();
  const {task}=await created.json();
  const repeated=await post('/api/obsidian/tasks',{request:'根據虛構筆記擬一份指南',profile:'quick'},createHeaders);
  assert.equal((await repeated.json()).task.id,task.id);
  assert.equal((await post('/api/obsidian/tasks',{request:'不同的任務內容'},createHeaders)).status,409);
  assert.equal((await(await app.fetch('/api/obsidian/tasks',{headers:bearer})).json()).tasks.length,1);
  const cards=await(await app.fetch(`/api/obsidian/tasks/${task.id}/work-cards`,{headers:bearer})).json();
  assert.equal(cards.cards.length,2);
  assert.equal(cards.cards[0].context.request,'根據虛構筆記擬一份指南');
  assert.equal(cards.cards[0].contextMetrics.input.tokens,null);
  assert.equal((await post(`/api/obsidian/tasks/${task.id}/approve`,{revision:task.revision},bearer)).status,400);
  assert.equal((await post('/api/obsidian/revoke',{id:access.id})).status,200);
  assert.equal((await app.fetch('/api/obsidian/tasks',{headers:bearer})).status,403);
  const restart=await requestApp(home);
  assert.equal((await restart.fetch('/api/obsidian/tasks',{headers:bearer})).status,403);
});
